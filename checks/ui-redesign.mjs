import {chromium} from 'playwright';
import {resolve} from 'node:path';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const context=await chromium.launchPersistentContext(resolve('work/ui-redesign-profile'),{channel:'chrome',headless:true,ignoreDefaultArgs:['--disable-extensions'],args:['--enable-unsafe-extension-debugging'],viewport:{width:1280,height:900}});
await mkdir('docs/screenshots',{recursive:true});
const shot=name=>resolve(`docs/screenshots/${name}.png`);
try {
  const cdp=await context.browser().newBrowserCDPSession();
  const {id}=await cdp.send('Extensions.loadUnpacked',{path:resolve('dist/extension')});
  let page=await context.newPage(); const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`chrome-extension://${id}/options.html`);
  const worker=context.serviceWorkers()[0]||await context.waitForEvent('serviceworker');
  await worker.evaluate(async()=>{await chrome.proxy.settings.clear({scope:'regular'});await chrome.storage.local.clear();});
  await cdp.send('Extensions.uninstall',{id});
  await cdp.send('Extensions.loadUnpacked',{path:resolve('dist/extension')});
  page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`chrome-extension://${id}/options.html`);
  await page.getByText('未连接',{exact:true}).waitFor();
  assert.equal(await page.locator('#rules-panel').getAttribute('open'),null);
  assert.equal(await page.locator('#toggle').isDisabled(),true);
  await page.screenshot({path:shot('settings-v4-empty'),fullPage:true,animations:'disabled'});
  const activeWorker=context.serviceWorkers().find(w=>new URL(w.url()).hostname===id)||await context.waitForEvent('serviceworker');
  await activeWorker.evaluate(()=>{
    const node=(name,port)=>({name,type:'http',server:'bridge.example.invalid',port,tls:true,username:`fixture-${port}`,password:'synthetic-only'});
    globalThis.fetch=async()=>new Response(JSON.stringify({proxies:[node('洛杉矶 · 专属线路',18443),node('东京 · 专属线路',18444),node('新加坡 · 专属线路',18445),{name:'原始 VLESS',type:'vless',server:'bridge.example.invalid',port:10443}]}),{status:200});
  });
  await page.getByRole('button',{name:'保存并更新'}).click();
  await page.locator('#error').filter({hasText:'请输入订阅地址'}).waitFor();
  await page.locator('#url').fill('https://subscription.example.invalid/test');
  await page.getByRole('button',{name:'显示订阅地址'}).click();
  assert.equal(await page.locator('#url').getAttribute('type'),'text');
  await page.getByRole('button',{name:'隐藏订阅地址'}).click();
  // An unsaved rule draft must survive a subscription import.
  await page.locator('#rules-panel>summary').click();
  await page.locator('#proxy').fill('draft.example.com');
  assert.equal(await page.locator('#rules-dirty').isVisible(),true);
  await page.getByRole('button',{name:'保存并更新'}).click();
  await page.getByText('3 条可用线路',{exact:true}).waitFor();
  assert.equal(await page.locator('#proxy').inputValue(),'draft.example.com');
  await page.getByText('1 个节点不支持浏览器代理',{exact:true}).waitFor();
  // Saving shows the normalized, de-duplicated list the background stored.
  await page.locator('#proxy').fill('*.Example.com.\nexample.com');
  await page.locator('#direct').fill('example.cn');
  await page.getByRole('button',{name:'保存规则'}).click();
  await page.getByText('网站规则已保存',{exact:true}).waitFor();
  await page.getByText('2 条自定义',{exact:true}).waitFor();
  assert.equal(await page.locator('#proxy').inputValue(),'example.com');
  assert.equal(await page.locator('#rules-dirty').isVisible(),false);
  await page.locator('#rules-panel>summary').click();
  await page.getByRole('radio',{name:'洛杉矶 · 专属线路'}).check();
  await page.getByRole('button',{name:'连接',exact:true}).click();
  await page.getByText('已连接',{exact:true}).waitFor();
  await page.waitForFunction(()=>!document.getElementById('toggle').disabled);
  assert.equal(await page.locator('.node.live .node-name').textContent(),'洛杉矶 · 专属线路');
  await page.mouse.move(0,0);
  await page.screenshot({path:shot('settings-v4'),fullPage:true,animations:'disabled'});
  await page.locator('#rules-panel>summary').click();
  await page.screenshot({path:shot('settings-v4-rules'),fullPage:true,animations:'disabled'});
  await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:shot('settings-v4-dark'),fullPage:true,animations:'disabled'});
  await page.emulateMedia({colorScheme:'light'});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:shot('settings-v4-mobile'),fullPage:true,animations:'disabled'});
  await page.goto(`chrome-extension://${id}/popup.html`);
  await page.setViewportSize({width:360,height:640});
  await page.getByText('已连接',{exact:true}).waitFor();
  assert.ok(await page.locator('.logo').evaluate(img=>img.complete&&img.naturalWidth>0),'Logo must load');
  await page.locator('body').screenshot({path:shot('popup-v4'),animations:'disabled'});
  await page.emulateMedia({colorScheme:'dark'});
  await page.locator('body').screenshot({path:shot('popup-v4-dark'),animations:'disabled'});
  await page.emulateMedia({colorScheme:'light'});
  await page.getByRole('radio',{name:'东京 · 专属线路'}).check();
  await page.getByText('已连接',{exact:true}).waitFor();
  assert.equal(await page.locator('.node.live .node-name').textContent(),'东京 · 专属线路');
  await page.getByRole('button',{name:'断开',exact:true}).click();
  await page.getByText('未连接',{exact:true}).waitFor();
  await page.locator('body').screenshot({path:shot('popup-v4-off'),animations:'disabled'});
  await activeWorker.evaluate(async()=>{await chrome.storage.local.clear();});
  assert.deepEqual(errors,[]);
  console.log('UI checks passed: empty state, import guard, rule draft kept, rule normalization, radio select/connect, responsive layout, dark mode, popup switch, disconnect.');
} finally {await context.close();}
